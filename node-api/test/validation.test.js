import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import {
  validateApiKeyBody,
  validateDomainName,
  validateFileTypes,
  validateOrigin,
  validatePattern,
  validateUrlBody,
  validateUsername,
} from '../src/lib/validation.js';

const code = (fn) => {
  try {
    fn();
  } catch (err) {
    return err.code;
  }
  return null;
};

describe('validateDomainName', () => {
  it('normalizes valid names', () => {
    assert.equal(validateDomainName(' Sub.Example.COM. '), 'sub.example.com');
  });

  it('rejects names without a dot, with scheme or with invalid labels', () => {
    for (const name of ['localhost', 'http://a.com', '-a.com', 'a..com', 'a_b.com']) {
      assert.equal(code(() => validateDomainName(name)), 'INVALID_DOMAIN', name);
    }
  });
});

describe('validateOrigin', () => {
  it('accepts a host and port', () => {
    assert.deepEqual(validateOrigin({ scheme: 'https', host: 'example.org', port: 443 }), {
      scheme: 'https',
      host: 'example.org',
      port: 443,
    });
  });

  it('rejects bad scheme, host with scheme and out of range port', () => {
    assert.equal(code(() => validateOrigin({ scheme: 'ftp', host: 'a', port: 1 })), 'INVALID_ORIGIN');
    assert.equal(code(() => validateOrigin({ scheme: 'http', host: 'http://a', port: 80 })), 'INVALID_ORIGIN');
    assert.equal(code(() => validateOrigin({ scheme: 'http', host: 'a', port: 70000 })), 'INVALID_ORIGIN');
    assert.equal(code(() => validateOrigin({ scheme: 'http', host: 'a', port: '80' })), 'INVALID_ORIGIN');
  });
});

describe('validatePattern', () => {
  it('accepts paths with wildcards', () => {
    assert.equal(validatePattern('/images/*'), '/images/*');
  });

  it('rejects paths without leading slash or with query string', () => {
    assert.equal(code(() => validatePattern('images/*')), 'INVALID_PATTERN');
    assert.equal(code(() => validatePattern('/a?b=1')), 'INVALID_PATTERN');
  });
});

describe('validateFileTypes', () => {
  it('normalizes extensions', () => {
    assert.deepEqual(validateFileTypes({ '.PNG': { ttlSeconds: 10, policy: 'LRU' } }), {
      png: { ttlSeconds: 10, policy: 'LRU' },
    });
  });

  it('accepts the default "*" entry', () => {
    assert.deepEqual(validateFileTypes({ '*': { ttlSeconds: 5, policy: 'RANDOM' } }), {
      '*': { ttlSeconds: 5, policy: 'RANDOM' },
    });
  });

  it('rejects unknown policies and non positive TTL', () => {
    assert.equal(code(() => validateFileTypes({ png: { ttlSeconds: 10, policy: 'LIFO' } })), 'INVALID_FILE_TYPES');
    assert.equal(code(() => validateFileTypes({ png: { ttlSeconds: 0, policy: 'LRU' } })), 'INVALID_FILE_TYPES');
    assert.equal(code(() => validateFileTypes([])), 'INVALID_FILE_TYPES');
  });
});

describe('validateUrlBody', () => {
  it('requires a known auth type', () => {
    const body = { pattern: '/*', cacheSizeBytes: 10, auth: { type: 'magic' } };
    assert.equal(code(() => validateUrlBody(body)), 'INVALID_AUTH_TYPE');
  });

  it('defaults fileTypes to an empty map', () => {
    const body = { pattern: '/*', cacheSizeBytes: 10, auth: { type: 'none' } };
    assert.deepEqual(validateUrlBody(body).fileTypes, {});
  });
});

describe('validateUsername', () => {
  it('rejects slashes and short names', () => {
    assert.equal(code(() => validateUsername('a/b')), 'INVALID_USERNAME');
    assert.equal(code(() => validateUsername('ab')), 'INVALID_USERNAME');
  });
});

describe('validateApiKeyBody', () => {
  const keyHash = 'a'.repeat(64);

  it('accepts hash and prefix generated by the UI', () => {
    assert.deepEqual(validateApiKeyBody({ name: 'postman', keyHash, prefix: 'pk_3fa91c2' }), {
      name: 'postman',
      keyHash,
      prefix: 'pk_3fa91c2',
    });
  });

  it('rejects a raw key instead of its hash', () => {
    const body = { name: 'x', keyHash: `pk_${keyHash}`, prefix: 'pk_3fa91c2' };
    assert.equal(code(() => validateApiKeyBody(body)), 'INVALID_API_KEY');
  });
});
